"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { toast } from "sonner";
import { Code2, FolderSymlink, Loader2, Plus, RefreshCw, Trash2, Upload } from "lucide-react";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";
import { PROJECT_SECTIONS } from "@/lib/config";
import { FileRow, SimpleText, formatDate, type FileItem } from "@/components/files/file-list";
import { DropZone } from "@/components/uploads/drop-zone";
import { filesFromInput, type PickedFile } from "@/components/uploads/drop-files";
import { FILES_CHANGED_EVENT, useUploads } from "@/components/uploads/upload-provider";
import { AgentIcon, branchColor, type AgentNode } from "./types";

type NodeDetail = {
  overview: string | null;
  overviewUpdatedAt: string | null;
  files: FileItem[];
  driveLinks: { id: string; name: string; driveFolderId: string; lastSyncedAt: string | null }[];
};

const COLLAPSED_FILES = 8;

/** Small dashed box: drop files on it, or click it to pick some. */
function FileDrop({
  onFiles,
  label,
  folder,
}: {
  onFiles: (files: PickedFile[]) => void;
  label: string;
  folder?: boolean;
}) {
  const ref = useRef<HTMLInputElement>(null);
  return (
    <DropZone onFiles={onFiles} className="rounded-lg">
      <input
        ref={ref}
        type="file"
        multiple
        className="hidden"
        {...(folder ? { webkitdirectory: "" } : {})}
        onChange={(e) => {
          onFiles(filesFromInput(e.target.files));
          e.target.value = "";
        }}
      />
      <button
        type="button"
        onClick={() => ref.current?.click()}
        className="w-full flex items-center justify-center gap-2 rounded-lg border border-dashed border-border px-3 py-3 text-xs text-muted-foreground hover:border-primary/60 hover:text-foreground transition-colors"
      >
        <Upload className="size-3.5 shrink-0" />
        {label}
      </button>
    </DropZone>
  );
}

function FileGroup({ label, files, onChanged }: { label?: string; files: FileItem[]; onChanged: () => void }) {
  const [expanded, setExpanded] = useState(false);
  const shown = expanded ? files : files.slice(0, COLLAPSED_FILES);
  return (
    <div className="flex flex-col">
      {label && <h4 className="text-[11px] uppercase tracking-wide text-muted-foreground px-2 pt-2 pb-1">{label}</h4>}
      <ul className="flex flex-col">
        {shown.map((f) => (
          <FileRow key={f.id} file={f} onChanged={onChanged} />
        ))}
      </ul>
      {files.length > COLLAPSED_FILES && (
        <button
          type="button"
          className="px-2 mt-1 text-xs text-muted-foreground hover:text-foreground w-fit"
          onClick={() => setExpanded((e) => !e)}
        >
          {expanded ? "Show less" : `Show all ${files.length}`}
        </button>
      )}
    </div>
  );
}

/**
 * The Overview tab of a node: its generated summary next to its files,
 * a drop box for new files, and its sub-nodes.
 */
export function NodeOverview({
  agent,
  subNodes,
  onSelect,
  onAddChild,
  updatingSummary = false,
}: {
  agent: AgentNode;
  subNodes: AgentNode[];
  onSelect: (agent: AgentNode) => void;
  onAddChild: () => void;
  /** The panel is rewriting the summary (after an edit). */
  updatingSummary?: boolean;
}) {
  const [data, setData] = useState<NodeDetail | null>(null);
  const [regenerating, setRegenerating] = useState(false);
  const refreshing = regenerating || updatingSummary;
  const [codeOpen, setCodeOpen] = useState(false);
  const autoGenerated = useRef(false);
  const { uploadFiles, uploadCode } = useUploads();
  const isBrain = agent.parentId === null;
  const isProject = agent.kind === "project";

  const load = useCallback(async () => {
    const res = await fetch(`/api/agents/${agent.id}`);
    if (res.ok) setData(await res.json());
  }, [agent.id]);

  useEffect(() => {
    let ignore = false;
    const refresh = () =>
      fetch(`/api/agents/${agent.id}`).then(async (res) => {
        if (!ignore && res.ok) setData(await res.json());
      });
    refresh();
    window.addEventListener(FILES_CHANGED_EVENT, refresh);
    return () => {
      ignore = true;
      window.removeEventListener(FILES_CHANGED_EVENT, refresh);
    };
  }, [agent.id]);

  const regenerate = useCallback(async () => {
    setRegenerating(true);
    const res = await fetch(`/api/agents/${agent.id}/overview`, { method: "POST" });
    setRegenerating(false);
    if (!res.ok) toast.error("Couldn't update the summary");
    load();
  }, [agent.id, load]);

  // The summary refreshes in the background a few seconds after files finish.
  const readyFiles = (data?.files ?? []).filter((f) => f.status === "ready");
  const lastProcessed = Math.max(0, ...readyFiles.map((f) => (f.processedAt ? Date.parse(f.processedAt) : 0)));
  const overviewStale =
    lastProcessed > 0 && (!data?.overviewUpdatedAt || Date.parse(data.overviewUpdatedAt) < lastProcessed);
  useEffect(() => {
    if (!overviewStale) return;
    const timer = setInterval(load, 8000);
    return () => clearInterval(timer);
  }, [overviewStale, load]);

  // Nodes that have something to summarize but no summary yet get one on first open.
  const hasContent = isBrain || subNodes.length > 0 || readyFiles.length > 0;
  useEffect(() => {
    if (!data || data.overview || overviewStale || updatingSummary || !hasContent || autoGenerated.current) return;
    autoGenerated.current = true;
    regenerate();
  }, [data, overviewStale, updatingSummary, hasContent, regenerate]);

  const toNode = (files: PickedFile[]) => uploadFiles(files, { agentId: agent.id, label: agent.name });

  async function syncLink(id: string) {
    const res = await fetch(`/api/drive-links/${id}`, { method: "POST" });
    if (!res.ok) toast.error(await res.text());
    else {
      const r = (await res.json()) as { added: number; updated: number; removed: number };
      toast.success(`Synced: ${r.added} new, ${r.updated} changed, ${r.removed} removed`);
    }
    window.dispatchEvent(new Event(FILES_CHANGED_EVENT));
  }

  async function unlink(id: string) {
    await fetch(`/api/drive-links/${id}`, { method: "DELETE" });
    toast.success("Folder unlinked (files stay in Drive)");
    load();
  }

  if (!data) {
    return <p className="text-sm text-muted-foreground text-center mt-16">Loading…</p>;
  }

  const docs = data.files.filter((f) => f.kind !== "code");
  const code = data.files.find((f) => f.kind === "code");
  const writing = refreshing || (!data.overview && overviewStale);

  const summary = (
    <section className="flex flex-col gap-2 min-w-0">
      <div className="flex items-center gap-2">
        <h3 className="text-sm font-medium flex-1">{isBrain ? "About you" : "Summary"}</h3>
        <Button variant="ghost" size="xs" onClick={regenerate} disabled={refreshing}>
          <RefreshCw className={cn(refreshing && "animate-spin")} />
          {refreshing ? "Updating…" : "Refresh"}
        </Button>
      </div>
      {data.overview ? (
        <>
          <SimpleText text={data.overview} className="text-muted-foreground" />
          <p className="text-[11px] text-muted-foreground/70">
            {overviewStale ? "Updating with new files…" : `Updated ${formatDate(data.overviewUpdatedAt)}`}
          </p>
        </>
      ) : (
        <p className="text-sm text-muted-foreground">
          {writing ? (
            <span className="flex items-center gap-2">
              <Loader2 className="size-3.5 animate-spin" /> Writing the summary…
            </span>
          ) : isBrain ? (
            "What the Brain knows about you shows up here. Chat with it or drop general files (CV, goals, schedule)."
          ) : (
            "Drop files here (a brief, rubric, study guide, your own work, feedback) and this becomes a summary of what's in them."
          )}
        </p>
      )}
    </section>
  );

  const fileColumn = (
    <section className="flex flex-col gap-2 min-w-0">
      <h3 className="text-sm font-medium">
        Files{docs.length > 0 && <span className="text-muted-foreground font-normal"> · {docs.length}</span>}
      </h3>
      <FileDrop onFiles={toNode} label={isProject ? "Drop files · the Brain picks the section" : "Drop files or click to add"} />
      {docs.length > 0 && (
        <div className="-mx-2 flex flex-col">
          {isProject ? (
            PROJECT_SECTIONS.map((s) => {
              const inSection = docs.filter((f) => (f.section ?? "other") === s.key);
              return inSection.length ? <FileGroup key={s.key} label={s.label} files={inSection} onChanged={load} /> : null;
            })
          ) : (
            <FileGroup files={docs} onChanged={load} />
          )}
        </div>
      )}

      {isProject && (
        <div className="flex flex-col gap-2 pt-2">
          <h3 className="text-sm font-medium flex items-center gap-1.5">
            <Code2 className="size-3.5" /> Code
          </h3>
          <FileDrop onFiles={(files) => uploadCode(agent.id, files)} folder label="Drop a code folder or zip" />
          {code && code.status !== "ready" && (
            <p className="text-xs text-muted-foreground flex items-center gap-2">
              {code.status === "failed" ? (
                <span className="text-destructive">{code.error}</span>
              ) : (
                <>
                  <Loader2 className="size-3.5 animate-spin" /> Reading {code.name}…
                </>
              )}
            </p>
          )}
          {code?.status === "ready" && (
            <div className="flex flex-col gap-1">
              <p className="text-xs text-muted-foreground">
                {code.name} · {formatDate(code.createdAt)}
              </p>
              {code.summary && (
                <>
                  <SimpleText text={code.summary} className={cn("text-xs text-muted-foreground", !codeOpen && "line-clamp-4")} />
                  <button
                    type="button"
                    className="text-xs text-muted-foreground hover:text-foreground w-fit"
                    onClick={() => setCodeOpen((o) => !o)}
                  >
                    {codeOpen ? "Show less" : "Show more"}
                  </button>
                </>
              )}
            </div>
          )}
        </div>
      )}

      {data.driveLinks.length > 0 && (
        <div className="flex flex-col gap-1 pt-2">
          <h3 className="text-sm font-medium">Linked Drive folders</h3>
          <ul className="flex flex-col gap-1">
            {data.driveLinks.map((l) => (
              <li key={l.id} className="flex items-center gap-1.5 text-sm">
                <FolderSymlink className="size-3.5 text-muted-foreground shrink-0" />
                <a
                  href={`https://drive.google.com/drive/folders/${l.driveFolderId}`}
                  target="_blank"
                  rel="noreferrer"
                  className="flex-1 truncate hover:underline"
                  title={`Synced ${formatDate(l.lastSyncedAt)}`}
                >
                  {l.name}
                </a>
                <Button variant="ghost" size="icon-xs" aria-label="Sync" onClick={() => syncLink(l.id)}>
                  <RefreshCw />
                </Button>
                <Button variant="ghost" size="icon-xs" aria-label="Unlink" onClick={() => unlink(l.id)}>
                  <Trash2 />
                </Button>
              </li>
            ))}
          </ul>
        </div>
      )}
    </section>
  );

  return (
    <div className="@container flex-1 min-h-0 overflow-y-auto">
      <div className="flex flex-col gap-5 p-4">
        <div className="grid gap-5 @xl:grid-cols-[minmax(0,1fr)_minmax(0,15rem)]">
          {summary}
          {fileColumn}
        </div>

        <section className="flex flex-col gap-2">
          <h3 className="text-sm font-medium">Connected nodes</h3>
          <div className="flex flex-wrap gap-1.5">
            {subNodes.map((child) => {
              const color = branchColor(child.branch);
              return (
                <button
                  key={child.id}
                  type="button"
                  onClick={() => onSelect(child)}
                  className="flex items-center gap-1.5 rounded-full border border-border px-2.5 py-1 text-xs hover:bg-background/60 transition-colors"
                >
                  <AgentIcon name={child.icon} className="size-3" style={{ color }} />
                  {child.name}
                </button>
              );
            })}
            <button
              type="button"
              onClick={onAddChild}
              className="flex items-center gap-1 rounded-full border border-dashed border-border px-2.5 py-1 text-xs text-muted-foreground hover:border-primary/60 hover:text-foreground transition-colors"
            >
              <Plus className="size-3" /> Add node
            </button>
          </div>
        </section>
      </div>
    </div>
  );
}
