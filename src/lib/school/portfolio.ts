// The "good Portflow": per collection and goal, the evidence that should be
// there, as Piet would build it. Read from the outcomes' criteria, the
// handbook's VE1/VE2/EE overviews (which evidence counts at which moment) and
// the roadmap's product texts. Matching Piet's real evidence to these rows is
// done by words in the evidence name (see mirror.ts).

export type EvidenceType = "link" | "file";
export type GoalCode = "OR" | "AA" | "MS" | "PL";

export type Target = {
  id: string;
  title: string;
  type: EvidenceType;
  goal: GoalCode;
  /** Portflow subgoal, e.g. "OR3". */
  sub: string;
  /** One or two sentences: what this piece of evidence is. */
  what: string;
  /** What has to be in it. */
  content: string[];
  /** Who has to give feedback on it, where the handbook really asks for that. */
  feedback?: string;
  /** Extra words that mark a feedback piece as belonging here (besides `words`). */
  feedbackWords?: string[];
  /** Words in the evidence name that mean "this is it". */
  words: string[];
  /** One row per sprint from this sprint on (0 = onboarding), up to the running one. */
  perSprint?: number;
  optional?: boolean;
};

export type Collection = { slug: string; name: string; color: string; description: string; goals: GoalCode[]; targets: Target[] };

